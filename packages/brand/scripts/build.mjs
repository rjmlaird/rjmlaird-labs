#!/usr/bin/env node
// Generates css/tokens.css, css/site-aliases.css and css/tailwind.css from
// src/brand.tokens.json and fails if any token pair misses WCAG 2.2 AA.
//   node scripts/build.mjs          write files, then check contrast
//   node scripts/build.mjs --check  fail if committed files differ (CI)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(path.join(root, "src/brand.tokens.json"), "utf8"));
const checkOnly = process.argv.includes("--check");

// ---------- colour maths ----------
const hex = (h) => { h = h.replace("#", ""); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)); };
const lin = (c) => { c /= 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
const lum = (h) => { const [r, g, b] = hex(h).map(lin); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };
const rgba = (h, a) => `rgba(${hex(h).join(",")},${a})`;
const v = (theme, k) => theme[k].$value;

// ---------- contrast gate ----------
const SURFACES = ["ink", "ink-2", "card", "lift"];
const ACCENTS = ["teal", "amber", "violet", "coral", "green", "sky", "watch"];
const failures = [];
const need = (theme, name, fg, bg, min) => {
  const r = ratio(v(theme, fg), v(theme, bg));
  if (r < min) failures.push(`${name}: ${fg} on ${bg} = ${r.toFixed(2)} (needs ${min})`);
};
for (const [name, theme] of Object.entries(tokens.theme)) {
  for (const s of SURFACES) {
    for (const t of ["text", "text-2", "text-3", ...ACCENTS]) need(theme, name, t, s, 4.5);
    need(theme, name, "focus", s, 3);
  }
  for (const a of ACCENTS) need(theme, name, "on-accent", a, 4.5);
}

// ---------- CSS generation ----------
const banner = "/* GENERATED by packages/brand/scripts/build.mjs from src/brand.tokens.json. Do not edit. */\n";
const colourNames = ["ink", "ink-2", "card", "lift", "text", "text-2", "text-3", "on-accent", "focus", "border", "border-strong"];
const themeBlock = (theme, scheme) => {
  const L = [`  color-scheme: ${scheme};`];
  for (const n of colourNames) L.push(`  --rj-${n}: ${v(theme, n)};`);
  for (const a of ACCENTS) {
    L.push(`  --rj-${a}: ${v(theme, a)};`);
    L.push(`  --rj-${a}-dim: ${rgba(v(theme, a), v(theme, "dim-alpha"))};`);
    L.push(`  --rj-${a}-line: ${rgba(v(theme, a), v(theme, "line-alpha"))};`);
  }
  return L.join("\n");
};
const list = (o) => Object.entries(o).filter(([k]) => !k.startsWith("$"));
const fam = (k) => tokens.font[k].$value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");

const shared = [
  ...["display", "body", "mono"].map((k) => `  --rj-font-${k}: ${fam(k)};`),
  ...list(tokens.radius).map(([k, x]) => `  --rj-radius-${k}: ${x};`),
  ...list(tokens.space).map(([k, x]) => `  --rj-space-${k}: ${x};`),
  ...list(tokens.layout).map(([k, x]) => `  --rj-${k}: ${x};`),
  ...list(tokens.motion).map(([k, x]) => `  --rj-motion-${k}: ${x};`),
  ...list(tokens.type).map(([k, x]) => `  --rj-fs-${k}: ${x};`),
  // semantic aliases: components should use these, not the raw palette
  "  --rj-bg: var(--rj-ink);",
  "  --rj-surface: var(--rj-card);",
  "  --rj-accent: var(--rj-teal);",
  "  --rj-accent-dim: var(--rj-teal-dim);",
  "  --rj-accent-line: var(--rj-teal-line);",
  "  --rj-link: var(--rj-teal);",
  "  --rj-ok: var(--rj-green);",
  "  --rj-warn: var(--rj-amber);",
  "  --rj-alert: var(--rj-coral);",
  "  --rj-info: var(--rj-sky);",
  ...tokens.viz.order.map((n, i) => `  --rj-viz-${i + 1}: var(--rj-${n});`),
].join("\n");

const tones = ["teal", "amber", "violet", "coral", "green", "sky"]
  .map((t) => `[data-tone="${t}"] { --rj-tone: var(--rj-${t}); --rj-tone-dim: var(--rj-${t}-dim); --rj-tone-line: var(--rj-${t}-line); }`)
  .join("\n");

const tokensCss = `${banner}
:root,
:root[data-theme="dark"] {
${themeBlock(tokens.theme.dark, "dark")}
${shared}
  --rj-tone: var(--rj-teal);
  --rj-tone-dim: var(--rj-teal-dim);
  --rj-tone-line: var(--rj-teal-line);
}

/* Explicit light theme, for print-style or editorial labs. Opt in with data-theme="light". */
:root[data-theme="light"] {
${themeBlock(tokens.theme.light, "light")}
}

/* data-theme="auto" follows the visitor's system setting. Dark remains the default everywhere else. */
@media (prefers-color-scheme: light) {
  :root[data-theme="auto"] {
${themeBlock(tokens.theme.light, "light").replace(/^/gm, "  ")}
  }
}

${tones}
`;

const siteAliasesCss = `${banner}/* Names used by rjmlaird.co.uk global.css, mapped to --rj-* tokens, so shared snippets from the main site work unchanged in labs. */
:root {
  --ink: var(--rj-ink); --ink2: var(--rj-ink-2); --card: var(--rj-card); --lift: var(--rj-lift);
  --w: var(--rj-text); --mb: var(--rj-text-2); --m: var(--rj-text-3);
${["teal:td:tb", "amber:ad:ab", "violet:vd:vb", "coral:cd:cb", "green:gd:gb", "sky:sd:sb"]
  .map((s) => { const [n, d, b] = s.split(":"); return `  --${n}: var(--rj-${n}); --${d}: var(--rj-${n}-dim); --${b}: var(--rj-${n}-line);`; }).join("\n")}
  --on-accent: var(--rj-on-accent); --bd: var(--rj-border); --bm: var(--rj-border-strong); --focus: var(--rj-focus);
  --font-display: var(--rj-font-display); --font-body: var(--rj-font-body); --font-mono: var(--rj-font-mono);
  --radius: var(--rj-radius-md); --content-max: var(--rj-content-max); --nav-h: var(--rj-nav-h);
}
`;

const twColours = [...SURFACES, "text", "text-2", "text-3", ...ACCENTS]
  .map((n) => `  --color-${n}: var(--rj-${n});`).join("\n");
const tailwindCss = `${banner}/* Tailwind v4: import after tokens.css. Gives utilities such as bg-ink, bg-card, text-text-2, text-teal, font-display. */
@theme inline {
${twColours}
  --color-border: var(--rj-border);
  --font-display: var(--rj-font-display);
  --font-sans: var(--rj-font-body);
  --font-mono: var(--rj-font-mono);
  --radius-sm: var(--rj-radius-sm);
  --radius-md: var(--rj-radius-md);
  --radius-lg: var(--rj-radius-lg);
}
`;

const outputs = { "css/tokens.css": tokensCss, "css/site-aliases.css": siteAliasesCss, "css/tailwind.css": tailwindCss };
let drift = false;
for (const [rel, body] of Object.entries(outputs)) {
  const file = path.join(root, rel);
  if (checkOnly) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== body) { console.error(`out of date: ${rel}`); drift = true; }
  } else writeFileSync(file, body);
}
if (failures.length) { console.error("Contrast failures:\n  " + failures.join("\n  ")); process.exit(1); }
if (drift) process.exit(1);
console.log(checkOnly ? "brand: generated files up to date, contrast OK" : "brand: wrote css/*, contrast OK");
