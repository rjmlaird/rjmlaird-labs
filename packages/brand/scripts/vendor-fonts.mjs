#!/usr/bin/env node
// Dev-time only: copies the latin + latin-ext variable woff2 files from @fontsource-variable/*
// into fonts/ and regenerates css/fonts.css. Run after bumping the fontsource devDependencies.
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const families = ["inter", "space-grotesk", "jetbrains-mono"];
const keep = /-(latin|latin-ext)-wght-normal/;
mkdirSync(path.join(root, "fonts/licences"), { recursive: true });

let css = "/* GENERATED by scripts/vendor-fonts.mjs. Self-hosted variable fonts (latin + latin-ext). SIL OFL 1.1: see fonts/licences. */\n";
for (const fam of families) {
  const pkg = path.join(root, "node_modules/@fontsource-variable", fam);
  if (!existsSync(pkg)) throw new Error(`Install devDependencies first: missing ${pkg}`);
  const src = readFileSync(path.join(pkg, "wght.css"), "utf8");
  for (const block of src.match(/\/\*[^*]*\*\/\s*@font-face\s*\{[^}]*\}/g) ?? []) {
    if (!keep.test(block)) continue;
    const file = /url\(\.\/files\/([^)]+)\)/.exec(block)[1];
    copyFileSync(path.join(pkg, "files", file), path.join(root, "fonts", file));
    css += "\n" + block.replace(`url(./files/${file})`, `url(../fonts/${file})`).replace(/\/\*[^*]*\*\/\s*/, "");
  }
  copyFileSync(path.join(pkg, "LICENSE"), path.join(root, "fonts/licences", `${fam}-OFL.txt`));
}
writeFileSync(path.join(root, "css/fonts.css"), css + "\n");
console.log("vendored fonts and wrote css/fonts.css");
